// Export the JS app's SVG icon set (src/js/ui/icons.js) for the Rust app:
//   node scripts/export-icons.mjs  ->  crates/inca/src/icons_svg.rs
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tmp = join(mkdtempSync(join(tmpdir(), 'inca-icons-')), 'icons.mjs');
writeFileSync(tmp, readFileSync(join(root, 'src/js/ui/icons.js'), 'utf8'));
const { ICONS } = await import(pathToFileURL(tmp).href);
const names = Object.keys(ICONS).sort();
let out = '//! The JS app\'s SVG icons (generated by scripts/export-icons.mjs — do not edit).\n\npub static ICONS: &[(&str, &str)] = &[\n';
for (const n of names) out += `    (${JSON.stringify(n)}, r##"${ICONS[n]}"##),\n`;
out += '];\n';
// command id -> icon name, from the `icon:` option of every registered command
const { readdirSync } = await import('node:fs');
const map = new Map();
for (const dir of ['src/js/core', 'src/js/ui']) for (const f of readdirSync(join(root, dir))) {
  const src = readFileSync(join(root, dir, f), 'utf8');
  for (const line of src.split('\n')) {
    const m = line.match(/(?:register|\bC|reg)\('([A-Za-z0-9_]+)',.*?\bicon: '([A-Za-z0-9_]+)'/);
    if (m && !map.has(m[1])) map.set(m[1], m[2]);
  }
}
out += '\n/// Command id -> icon name (from the JS command registry).\npub static CMD_ICONS: &[(&str, &str)] = &[\n';
for (const [k, v] of [...map].sort()) out += `    (${JSON.stringify(k)}, ${JSON.stringify(v)}),\n`;
out += '];\n';
writeFileSync(join(root, 'crates/inca/src/icons_svg.rs'), out);
console.log(`${names.length} icons, ${map.size} command icons`);
